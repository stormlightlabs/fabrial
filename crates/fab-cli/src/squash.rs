//! The squash commit body Branch PR and the Review gate both build from a
//! pull request's description: its text, then `Merged from <branch>.` and the
//! owner's Co-authored-by line.
//!
//! The description stops at the footer line Branch PR writes, so the text
//! after it stays out. The body Branch PR generated before the footer existed
//! counts as empty. Lines that attribute the work to an agent are dropped,
//! quoted or not and in any case: Co-authored-by and Claude-Session trailers,
//! a `Session:` line naming a link, "Generated with" lines, the robot emoji,
//! and Claude Code session and Codex task links. No agent attribution reaches
//! main. Code blocks get no special treatment.

/// The line that ends the part of a pull request body the squash keeps.
pub const FOOTER: &str = "<!-- fabrial:footer";

/// The squash body for a description: its kept text, a blank line, then
/// `Merged from <branch>.` and the owner's trailer. A description with
/// nothing kept gives the plain `Merged from <branch>.` body.
pub fn body(description: &str, branch: &str, trailer: &str) -> String {
    let text = kept_text(description);
    let merged = format!("Merged from {branch}.\n\nCo-authored-by: {trailer}");
    if text.is_empty() { merged } else { format!("{text}\n\n{merged}") }
}

/// The description's text that the squash keeps, without blank lines at
/// either end.
pub fn kept_text(description: &str) -> String {
    let description = description.replace('\r', "");
    let mut footer = false;
    let mut lines = Vec::new();
    for line in description.lines() {
        if line.starts_with(FOOTER) {
            footer = true;
            break;
        }
        if !attributes_an_agent(line) {
            lines.push(line);
        }
    }
    let blank = |l: &&str| l.trim().is_empty();
    let first = lines.iter().position(|l| !blank(l)).unwrap_or(lines.len());
    let last = lines.iter().rposition(|l| !blank(l)).map_or(first, |i| i + 1);
    let lines = &lines[first..last];
    // The body Branch PR wrote before the footer existed is a list of commit
    // subjects under `From <branch>:`, which says nothing the title does not.
    if !footer && lines.first().is_some_and(|l| is_old_generated_intro(l)) {
        return String::new();
    }
    lines.join("\n")
}

/// Whether a line credits an agent, read without quote marks, leading space
/// or case.
fn attributes_an_agent(line: &str) -> bool {
    if line.contains('🤖') {
        return true;
    }
    let bare = line
        .trim_start_matches(|c: char| c.is_whitespace() || c == '>')
        .to_ascii_lowercase();
    let generated = ["generated with ", "generated by "].iter().any(|phrase| {
        bare.match_indices(phrase).any(|(i, _)| {
            let rest = &bare[i + phrase.len()..];
            rest.contains("claude") || rest.contains("codex")
        })
    });
    bare.starts_with("co-authored-by:")
        || bare.starts_with("claude-session:")
        || bare
            .strip_prefix("session:")
            .is_some_and(|rest| rest.contains("http://") || rest.contains("https://"))
        || generated
        || bare.contains("claude.ai/code/session_")
        || bare.contains("chatgpt.com/codex/")
}

/// Whether a line is `From `<branch>`:`, the old generated body's first line.
fn is_old_generated_intro(line: &str) -> bool {
    line.strip_prefix("From `")
        .and_then(|rest| rest.strip_suffix("`:"))
        .is_some_and(|branch| !branch.is_empty() && !branch.contains('`'))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_body_ends_with_the_branch_and_the_owner() {
        assert_eq!(
            body("Why it changed.\n", "storm/x", "A <a@b>"),
            "Why it changed.\n\nMerged from storm/x.\n\nCo-authored-by: A <a@b>"
        );
        assert_eq!(
            body("", "storm/x", "A <a@b>"),
            "Merged from storm/x.\n\nCo-authored-by: A <a@b>"
        );
    }

    #[test]
    fn the_footer_ends_the_kept_text() {
        let description = "Keep.\r\n\r\n<!-- fabrial:footer: the text above -->\nFrom `storm/x`.\n";
        assert_eq!(kept_text(description), "Keep.");
    }

    #[test]
    fn agent_attribution_goes_in_any_case_and_quoted() {
        let description = "Keep.\n\
            Co-Authored-By: Claude <noreply@anthropic.com>\n\
            > claude-session: https://claude.ai/code/session_1\n\
            🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\
            Generated by Codex\n\
            See https://claude.ai/code/session_abc\n\
            Task: https://chatgpt.com/codex/tasks/1\n\
            Also keep.\n";
        assert_eq!(kept_text(description), "Keep.\nAlso keep.");
    }

    #[test]
    fn generated_lines_need_an_agent_name_after_them() {
        assert_eq!(kept_text("Generated with care.\n"), "Generated with care.");
        assert_eq!(kept_text("Code generated by protoc.\n"), "Code generated by protoc.");
    }

    #[test]
    fn a_session_line_goes_only_when_it_names_a_link() {
        let description = "Keep.\nSession: tokens now expire.\nSession: https://pi.dev/s/abc\n\
            > Session: <https://pi.dev/s/abc>\nSession: [run](https://x.io/s)\n";
        assert_eq!(kept_text(description), "Keep.\nSession: tokens now expire.");
    }

    #[test]
    fn code_blocks_are_text_like_any_other() {
        let description =
            "Keep.\n````\n```\nCo-authored-by: A <a@b>\n````\nAlso kept.\n<!-- fabrial:footer -->\nGone.\n";
        assert_eq!(kept_text(description), "Keep.\n````\n```\n````\nAlso kept.");
    }

    #[test]
    fn the_old_generated_body_counts_as_empty_without_a_footer() {
        assert_eq!(kept_text("\nFrom `storm/x`:\n- Add a\n"), "");
        let footed = "From `storm/x`:\n- Add a\n<!-- fabrial:footer -->\n";
        assert_eq!(kept_text(footed), "From `storm/x`:\n- Add a");
        assert_eq!(kept_text("From `storm/x`: a note\n"), "From `storm/x`: a note");
    }

    #[test]
    fn blank_lines_at_either_end_go() {
        assert_eq!(kept_text("\n \nKeep.\n\nAlso.\n\t\n"), "Keep.\n\nAlso.");
        assert_eq!(kept_text("Co-authored-by: A <a@b>\n"), "");
    }
}
